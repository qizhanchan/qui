//go:build ignore

// idct_gen writes idct_unrolled.go: the inverse DCTs of transform.go's
// idct (spec 7.13.2.3) unrolled into straight-line code per size, with
// the bit-reversed input order and the butterfly cosines resolved at
// generation time. The schedule below is idct's, statement for
// statement; TestIdctUnrolled pins the two equal.
//
//	go run idct_gen.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"math"
	"os"
)

var cosLookup [65]int64

func cos128(angle int) int64 {
	a := angle & 255
	switch {
	case a <= 64:
		return cosLookup[a]
	case a <= 128:
		return -cosLookup[128-a]
	case a <= 192:
		return -cosLookup[a-128]
	}
	return cosLookup[256-a]
}

func sin128(angle int) int64 { return cos128(angle - 64) }

func brev(numBits, x int) int {
	r := 0
	for i := 0; i < numBits; i++ {
		r |= (x >> i & 1) << (numBits - 1 - i)
	}
	return r
}

var out bytes.Buffer

func emit(format string, args ...any) { fmt.Fprintf(&out, format+"\n", args...) }

// term renders v*k for a constant k.
func term(v string, k int64) string {
	return fmt.Sprintf("int64(%s)*%d", v, k)
}

func bfly(a, b, angle int, flip bool) {
	c, s := cos128(angle), sin128(angle)
	x, y := fmt.Sprintf("t%d", a), fmt.Sprintf("t%d", b)
	ra := fmt.Sprintf("round12(%s - %s)", term(x, c), term(y, s))
	rb := fmt.Sprintf("round12(%s + %s)", term(x, s), term(y, c))
	if flip {
		ra, rb = rb, ra
	}
	emit("%s, %s = %s, %s", x, y, ra, rb)
}

func hada(a, b int, flip bool) {
	if flip {
		a, b = b, a
	}
	emit("t%d, t%d = t%d+t%d, t%d-t%d", a, b, a, b, a, b)
}

// schedule is transform.go's idct with t replaced by the emitters.
func schedule(n int) {
	if n == 6 {
		for i := 0; i < 16; i++ {
			bfly(32+i, 63-i, 63-4*brev(4, i), false)
		}
	}
	if n >= 5 {
		for i := 0; i < 8; i++ {
			bfly(16+i, 31-i, 6+(brev(3, 7-i)<<3), false)
		}
	}
	if n == 6 {
		for i := 0; i < 16; i++ {
			hada(32+i*2, 33+i*2, i&1 != 0)
		}
	}
	if n >= 4 {
		for i := 0; i < 4; i++ {
			bfly(8+i, 15-i, 12+(brev(2, 3-i)<<4), false)
		}
	}
	if n >= 5 {
		for i := 0; i < 8; i++ {
			hada(16+2*i, 17+2*i, i&1 != 0)
		}
	}
	if n == 6 {
		for i := 0; i < 4; i++ {
			for j := 0; j < 2; j++ {
				bfly(62-i*4-j, 33+i*4+j, 60-16*brev(2, i)+64*j, true)
			}
		}
	}
	if n >= 3 {
		for i := 0; i < 2; i++ {
			bfly(4+i, 7-i, 56-32*i, false)
		}
	}
	if n >= 4 {
		for i := 0; i < 4; i++ {
			hada(8+2*i, 9+2*i, i&1 != 0)
		}
	}
	if n >= 5 {
		for i := 0; i < 2; i++ {
			for j := 0; j < 2; j++ {
				bfly(30-4*i-j, 17+4*i+j, 24+(j<<6)+((1-i)<<5), true)
			}
		}
	}
	if n == 6 {
		for i := 0; i < 8; i++ {
			for j := 0; j < 2; j++ {
				hada(32+i*4+j, 35+i*4-j, i&1 != 0)
			}
		}
	}
	for i := 0; i < 2; i++ {
		bfly(2*i, 2*i+1, 32+16*i, i == 0)
	}
	if n >= 3 {
		for i := 0; i < 2; i++ {
			hada(4+2*i, 5+2*i, i != 0)
		}
	}
	if n >= 4 {
		for i := 0; i < 2; i++ {
			bfly(14-i, 9+i, 48+64*i, true)
		}
	}
	if n >= 5 {
		for i := 0; i < 4; i++ {
			for j := 0; j < 2; j++ {
				hada(16+4*i+j, 19+4*i-j, i&1 != 0)
			}
		}
	}
	if n == 6 {
		for i := 0; i < 2; i++ {
			for j := 0; j < 4; j++ {
				bfly(61-i*8-j, 34+i*8+j, 56-i*32+(j>>1)*64, true)
			}
		}
	}
	for i := 0; i < 2; i++ {
		hada(i, 3-i, false)
	}
	if n >= 3 {
		bfly(6, 5, 32, true)
	}
	if n >= 4 {
		for i := 0; i < 2; i++ {
			for j := 0; j < 2; j++ {
				hada(8+4*i+j, 11+4*i-j, i != 0)
			}
		}
	}
	if n >= 5 {
		for i := 0; i < 4; i++ {
			bfly(29-i, 18+i, 48+(i>>1)*64, true)
		}
	}
	if n == 6 {
		for i := 0; i < 4; i++ {
			for j := 0; j < 4; j++ {
				hada(32+8*i+j, 39+8*i-j, i&1 != 0)
			}
		}
	}
	if n >= 3 {
		for i := 0; i < 4; i++ {
			hada(i, 7-i, false)
		}
	}
	if n >= 4 {
		for i := 0; i < 2; i++ {
			bfly(13-i, 10+i, 32, true)
		}
	}
	if n >= 5 {
		for i := 0; i < 2; i++ {
			for j := 0; j < 4; j++ {
				hada(16+i*8+j, 23+i*8-j, i != 0)
			}
		}
	}
	if n == 6 {
		for i := 0; i < 8; i++ {
			a := 112
			if i < 4 {
				a = 48
			}
			bfly(59-i, 36+i, a, true)
		}
	}
	if n >= 4 {
		for i := 0; i < 8; i++ {
			hada(i, 15-i, false)
		}
	}
	if n >= 5 {
		for i := 0; i < 4; i++ {
			bfly(27-i, 20+i, 32, true)
		}
	}
	if n == 6 {
		for i := 0; i < 8; i++ {
			hada(32+i, 47-i, false)
			hada(48+i, 63-i, true)
		}
	}
	if n >= 5 {
		for i := 0; i < 16; i++ {
			hada(i, 31-i, false)
		}
	}
	if n == 6 {
		for i := 0; i < 8; i++ {
			bfly(55-i, 40+i, 32, true)
		}
	}
	if n == 6 {
		for i := 0; i < 32; i++ {
			hada(i, 63-i, false)
		}
	}
}

func main() {
	for i := range cosLookup {
		cosLookup[i] = int64(math.Round(4096 * math.Cos(float64(i)*math.Pi/128)))
	}
	emit("// Code generated by idct_gen.go; DO NOT EDIT.\n")
	emit("package av1\n")
	for n := 2; n <= 6; n++ {
		n0 := 1 << n
		emit("// idct%d is idct(t, %d) unrolled.", n0, n)
		emit("func idct%d(t []int32) {", n0)
		emit("_ = t[%d]", n0-1)
		for i := 0; i < n0; i++ {
			emit("t%d := t[%d]", i, brev(n, i))
		}
		schedule(n)
		for i := 0; i < n0; i++ {
			emit("t[%d] = t%d", i, i)
		}
		emit("}\n")
	}
	src, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("idct_unrolled.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
