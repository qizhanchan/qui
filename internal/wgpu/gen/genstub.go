//go:build ignore

// genstub writes stub_gen.go: the exported API of the cgo binding for
// builds without cgo (CGO_ENABLED=0, js/wasm), so code that uses package
// gpu compiles everywhere and finds out at run time — Shared / Load
// report ErrUnavailable — instead of failing to build.
//
// Every exported type, constant and function of the cgo files is
// mirrored: constants take their values from dawn_webgpu.h, structs keep
// their exported fields (handle fields are dropped), and functions return
// zero values (ErrUnavailable for an error).
//
//	go generate ./internal/wgpu
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"regexp"
	"strconv"
	"strings"
)

var sources = []string{"wgpu.go", "layout.go", "surface.go", "load.go", "timestamp.go"}

var outPath = flag.String("o", "stub_gen.go", "output file")

var (
	enumRe  = regexp.MustCompile(`^\s+(WGPU[A-Za-z0-9_]+) = (0x[0-9A-Fa-f]+|\d+),?$`)
	constRe = regexp.MustCompile(`^static const WGPU[A-Za-z0-9]+ (WGPU[A-Za-z0-9_]+) = (0x[0-9A-Fa-f]+|\d+)(?:ULL|U)?;$`)
)

func main() {
	flag.Parse()
	vals := headerValues("dawn_webgpu.h")
	fset := token.NewFileSet()
	var out bytes.Buffer
	out.WriteString(`// Code generated by gen/genstub.go; DO NOT EDIT.

//go:build !cgo || js

package wgpu

`)
	var body bytes.Buffer
	for _, name := range sources {
		src, err := os.ReadFile(name)
		if err != nil {
			log.Fatal(err)
		}
		f, err := parser.ParseFile(fset, name, src, parser.ParseComments)
		if err != nil {
			log.Fatal(err)
		}
		text := func(n ast.Node) string {
			return string(src[fset.Position(n.Pos()).Offset:fset.Position(n.End()).Offset])
		}
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.GenDecl:
				genDecl(&body, d, text, vals)
			case *ast.FuncDecl:
				funcDecl(&body, d, text)
			}
		}
	}
	var imports []string
	for _, pkg := range []string{"image", "time", "unsafe"} {
		if bytes.Contains(body.Bytes(), []byte(pkg+".")) {
			imports = append(imports, strconv.Quote(pkg))
		}
	}
	if len(imports) > 0 {
		fmt.Fprintf(&out, "import (\n%s\n)\n\n", strings.Join(imports, "\n"))
	}
	out.Write(body.Bytes())
	res, err := format.Source(out.Bytes())
	if err != nil {
		os.WriteFile("stub_gen.go.broken", out.Bytes(), 0o644)
		log.Fatalf("format: %v (see stub_gen.go.broken)", err)
	}
	if err := os.WriteFile(*outPath, res, 0o644); err != nil {
		log.Fatal(err)
	}
}

func headerValues(path string) map[string]string {
	f, err := os.Open(path)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	vals := map[string]string{}
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		line := sc.Text()
		if m := enumRe.FindStringSubmatch(line); m != nil {
			vals[m[1]] = m[2]
		} else if m := constRe.FindStringSubmatch(line); m != nil {
			vals[m[1]] = m[2]
		}
	}
	return vals
}

func usesC(n ast.Node) bool {
	found := false
	ast.Inspect(n, func(n ast.Node) bool {
		if s, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := s.X.(*ast.Ident); ok && id.Name == "C" {
				found = true
			}
		}
		return !found
	})
	return found
}

func genDecl(w *bytes.Buffer, d *ast.GenDecl, text func(ast.Node) string, vals map[string]string) {
	switch d.Tok {
	case token.TYPE:
		for _, s := range d.Specs {
			ts := s.(*ast.TypeSpec)
			if !ts.Name.IsExported() {
				continue
			}
			st, isStruct := ts.Type.(*ast.StructType)
			if !isStruct {
				if usesC(ts.Type) {
					log.Fatalf("type %s: non-struct C type", ts.Name.Name)
				}
				fmt.Fprintf(w, "type %s\n\n", text(ts))
				continue
			}
			fmt.Fprintf(w, "type %s struct {\n", ts.Name.Name)
			for _, fld := range st.Fields.List {
				if usesC(fld.Type) {
					continue
				}
				var names []string
				for _, n := range fld.Names {
					if n.IsExported() {
						names = append(names, n.Name)
					}
				}
				if len(fld.Names) == 0 || len(names) == 0 {
					continue
				}
				fmt.Fprintf(w, "\t%s %s\n", strings.Join(names, ", "), text(fld.Type))
			}
			fmt.Fprintf(w, "}\n\n")
		}
	case token.CONST:
		var lines []string
		for _, s := range d.Specs {
			vs := s.(*ast.ValueSpec)
			exported := false
			for _, n := range vs.Names {
				exported = exported || n.IsExported()
			}
			if !exported {
				continue
			}
			if len(vs.Values) == 0 || !usesC(vs) {
				if len(vs.Values) == 0 && len(lines) == 0 {
					log.Fatalf("const %s: implicit value", vs.Names[0].Name)
				}
				lines = append(lines, text(vs))
				continue
			}
			if len(vs.Names) != 1 || len(vs.Values) != 1 {
				log.Fatalf("const %s: one name per C value expected", vs.Names[0].Name)
			}
			sel, ok := vs.Values[0].(*ast.SelectorExpr)
			if !ok {
				log.Fatalf("const %s: value is not C.NAME", vs.Names[0].Name)
			}
			v, ok := vals[sel.Sel.Name]
			if !ok {
				log.Fatalf("const %s: %s not in dawn_webgpu.h", vs.Names[0].Name, sel.Sel.Name)
			}
			typ := ""
			if vs.Type != nil {
				typ = " " + text(vs.Type)
			}
			lines = append(lines, fmt.Sprintf("%s%s = %s", vs.Names[0].Name, typ, v))
		}
		if len(lines) > 0 {
			fmt.Fprintf(w, "const (\n\t%s\n)\n\n", strings.Join(lines, "\n\t"))
		}
	case token.VAR:
		for _, s := range d.Specs {
			vs := s.(*ast.ValueSpec)
			if !vs.Names[0].IsExported() {
				continue
			}
			if usesC(vs) {
				log.Fatalf("var %s uses C", vs.Names[0].Name)
			}
			fmt.Fprintf(w, "var %s\n\n", text(vs))
		}
	}
}

func funcDecl(w *bytes.Buffer, d *ast.FuncDecl, text func(ast.Node) string) {
	if !d.Name.IsExported() {
		return
	}
	recv := ""
	if d.Recv != nil {
		t := d.Recv.List[0].Type
		if st, ok := t.(*ast.StarExpr); ok {
			t = st.X
		}
		if id, ok := t.(*ast.Ident); !ok || !id.IsExported() {
			return
		}
		// Receiver names are dropped: the stub bodies never use them.
		recv = "(_ " + text(d.Recv.List[0].Type) + ") "
	}
	if usesC(d.Type) {
		log.Fatalf("func %s: C in signature", d.Name.Name)
	}
	params := blankParams(d.Type.Params, text)
	results := ""
	var zeros []string
	if d.Type.Results != nil {
		var rs []string
		for _, r := range d.Type.Results.List {
			n := max(1, len(r.Names))
			for i := 0; i < n; i++ {
				rs = append(rs, text(r.Type))
				zeros = append(zeros, zero(r.Type, text(r.Type)))
			}
		}
		results = " " + strings.Join(rs, ", ")
		if len(rs) > 1 {
			results = " (" + strings.Join(rs, ", ") + ")"
		}
	}
	fmt.Fprintf(w, "func %s%s(%s)%s {", recv, d.Name.Name, params, results)
	if len(zeros) > 0 {
		fmt.Fprintf(w, " return %s ", strings.Join(zeros, ", "))
	}
	fmt.Fprintf(w, "}\n\n")
}

// zero is the zero value of t: ErrUnavailable for an error.
func zero(t ast.Expr, s string) string {
	switch t := t.(type) {
	case *ast.StarExpr, *ast.ArrayType, *ast.MapType, *ast.FuncType, *ast.ChanType, *ast.InterfaceType:
		if a, ok := t.(*ast.ArrayType); ok && a.Len != nil {
			return s + "{}"
		}
		return "nil"
	case *ast.SelectorExpr:
		if s == "unsafe.Pointer" {
			return "nil"
		}
	case *ast.Ident:
		switch t.Name {
		case "error":
			return "ErrUnavailable"
		case "bool":
			return "false"
		case "string":
			return `""`
		case "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", "uint64",
			"uintptr", "float32", "float64", "byte", "rune":
			return "0"
		}
	}
	return "*new(" + s + ")"
}

func blankParams(fl *ast.FieldList, text func(ast.Node) string) string {
	var ps []string
	for _, p := range fl.List {
		n := max(1, len(p.Names))
		for i := 0; i < n; i++ {
			ps = append(ps, "_ "+text(p.Type))
		}
	}
	return strings.Join(ps, ", ")
}
