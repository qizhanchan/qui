//go:build ignore

// genproc writes procs_gen.c: one definition of every wgpu* entry point
// declared in dawn_webgpu.h, forwarding through a function pointer
// that quiWGPULoadProcs fills from the Dawn library loaded at run time.
// qui therefore links against no WebGPU library — a build without Dawn
// installed compiles and runs (the WebGPU renderer reports itself
// unavailable).
//
//	go generate ./internal/wgpu
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"log"
	"os"
	"regexp"
	"strings"
)

var decl = regexp.MustCompile(`^WGPU_EXPORT (.+?)\b(wgpu[A-Za-z0-9]+)\((.*)\) WGPU_FUNCTION_ATTRIBUTE;$`)

func main() {
	f, err := os.Open("dawn_webgpu.h")
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	var b bytes.Buffer
	b.WriteString("// Code generated by gen/genproc.go from dawn_webgpu.h. DO NOT EDIT.\n\n")
	b.WriteString("//go:build cgo && !js\n\n")
	b.WriteString("#include \"dawn_webgpu.h\"\n#include <stddef.h>\n\n")
	var names []string
	var defs bytes.Buffer
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		m := decl.FindStringSubmatch(strings.TrimSpace(sc.Text()))
		if m == nil {
			continue
		}
		ret, name, params := strings.TrimSpace(m[1]), m[2], strings.TrimSpace(m[3])
		short := strings.TrimPrefix(name, "wgpu")
		var args []string
		if params != "void" && params != "" {
			for _, p := range strings.Split(params, ",") {
				p = strings.TrimSpace(p)
				if strings.ContainsAny(p, "()") {
					log.Fatalf("%s: unsupported parameter %q", name, p)
				}
				fields := strings.Fields(strings.NewReplacer("*", " * ").Replace(p))
				args = append(args, fields[len(fields)-1])
			}
		}
		names = append(names, short)
		fmt.Fprintf(&defs, "static WGPUProc%s p_%s;\n", short, short)
		call := fmt.Sprintf("p_%s(%s)", short, strings.Join(args, ", "))
		if strings.TrimSpace(strings.ReplaceAll(ret, "WGPU_NULLABLE", "")) == "void" {
			fmt.Fprintf(&defs, "%s %s(%s) { %s; }\n", ret, name, params, call)
		} else {
			fmt.Fprintf(&defs, "%s %s(%s) { return %s; }\n", ret, name, params, call)
		}
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	b.Write(defs.Bytes())
	b.WriteString("\n// quiWGPULoadProcs resolves every entry point through sym and returns\n")
	b.WriteString("// how many the library lacks (their forwarders must then not be called).\n")
	b.WriteString("int quiWGPULoadProcs(void* (*sym)(const char*)) {\n\tint missing = 0;\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\tif (!(p_%s = (WGPUProc%s)sym(\"wgpu%s\"))) missing++;\n", n, n, n)
	}
	b.WriteString("\treturn missing;\n}\n")
	if err := os.WriteFile("procs_gen.c", b.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("procs_gen.c: %d entry points", len(names))
}
